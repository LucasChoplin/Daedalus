//affiche la map et la centre a l'ecran
void drawMap(SDL_Renderer* renderer, int offsetX, int offsetY){
    SDL_Rect src;
    SDL_Texture* atlas = getAtlasTexture();
    for(int y = 0; y < MAP_HEIGHT; y++){ //parcours de la map
        for(int x = 0; x < MAP_WIDTH; x++){ 
            int tileID = map[y][x];
            src = getTileRect(tileID);

            SDL_Rect destRect = {x * TILE_SIZE + offsetX, y * TILE_SIZE + offsetY, TILE_SIZE, TILE_SIZE};

            SDL_RenderCopy(renderer, atlas, &src, &destRect);
        }
    }
}

